def png_chunk(kind: bytes, payload: bytes) -> bytes:
    checksum = binascii.crc32(kind + payload) & 0xFFFFFFFF
    return struct.pack(">I", len(payload)) + kind + payload + struct.pack(">I", checksum)


def texture_png(asset: str, channel: str, udim: int, size: int = 128) -> bytes:
    seed = int.from_bytes(hashlib.sha256(f"{asset}:{channel}:{udim}".encode()).digest()[:4])
    rows = bytearray()
    for y in range(size):
        rows.append(0)
        for x in range(size):
            checker = ((x // 16) + (y // 16)) % 2
            if channel == "N":
                red = 112 + ((x + seed) % 32)
                green = 112 + ((y + seed // 7) % 32)
                blue = 245
            elif channel == "R":
                value = 45 + ((x * 2 + y + seed) % 180)
                red = green = blue = value
            else:
                red = (seed + x * 3 + checker * 55) % 256
                green = (seed // 3 + y * 2 + checker * 35) % 256
                blue = (seed // 11 + x + y + checker * 20) % 256
            rows.extend((red, green, blue))
    header = struct.pack(">IIBBBBB", size, size, 8, 2, 0, 0, 0)
    return (
        b"\x89PNG\r\n\x1a\n"
        + png_chunk(b"IHDR", header)
        + png_chunk(b"IDAT", zlib.compress(bytes(rows), level=9))
        + png_chunk(b"IEND", b"")
    )


def ascii_fbx(asset: str, version: int) -> bytes:
    identifier = int.from_bytes(hashlib.sha256(f"{asset}:{version}".encode()).digest()[:7], "big")
    text = f"""; FBX 7.4.0 project file
; Synthetic redistributable demo mesh generated by Asset Delivery Organizer.
FBXHeaderExtension:  {{
    FBXHeaderVersion: 1003
    FBXVersion: 7400
}}
Objects:  {{
    Geometry: {identifier}, \"Geometry::{asset}\", \"Mesh\" {{
        Vertices: *24 {{
            a: -50,-50,0,50,-50,0,50,50,0,-50,50,0,-50,-50,100,50,-50,100,50,50,100,-50,50,100
        }}
        PolygonVertexIndex: *24 {{
            a: 0,1,2,-4,4,7,6,-6,0,4,5,-2,1,5,6,-3,2,6,7,-4,4,0,3,-8
        }}
    }}
    Model: {identifier + 1}, \"Model::{asset}\", \"Mesh\" {{
        Version: {version}
    }}
}}
Connections:  {{
    C: \"OO\",{identifier},{identifier + 1}
}}
"""
    return text.encode("utf-8")


def ascii_usd(asset: str, version: int) -> bytes:
    return f"""#usda 1.0
(
    customLayerData = {{ string generator = \"asset-delivery-organizer-demo\" }}
)
def Xform \"{asset}\" {{
    custom int deliveryVersion = {version}
    def Mesh \"PreviewMesh\" {{
        int[] faceVertexCounts = [3]
        int[] faceVertexIndices = [0, 1, 2]
        point3f[] points = [(0, 0, 0), (100, 0, 0), (0, 100, 0)]
    }}
}}
""".encode()


def add_texture_set(
    files: dict[str, bytes],
    asset: str,
    *,
    directory: str = "Textures",
    udims: tuple[int, ...] = (1001,),
    channels: tuple[str, ...] = ("B", "N", "R"),
) -> None:
    for udim in udims:
        for channel in channels:
            files[f"{directory}/T_{asset}_{channel}.{udim}.png"] = texture_png(asset, channel, udim)


