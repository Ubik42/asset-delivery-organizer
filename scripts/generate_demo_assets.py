def manifest(specs: list[ScenarioSpec]) -> dict[str, object]:
    scenarios = []
    for spec in specs:
        facts = [
            {
                "relative_path": path,
                "size_bytes": len(payload),
                "sha256": hashlib.sha256(payload).hexdigest(),
            }
            for path, payload in sorted(spec.files.items())
        ]
        scenarios.append(
            {
                "scenario_id": spec.scenario_id,
                "title": spec.title,
                "description": spec.description,
                "file_count": len(facts),
                "total_bytes": sum(item["size_bytes"] for item in facts),
                "files": facts,
            }
        )
    return {
        "schema_id": "asset-delivery-organizer-demo-assets/1",
        "generator_version": GENERATOR_VERSION,
        "license": "CC0-1.0 synthetic fixtures",
        "scenarios": scenarios,
    }


def serialized(value: object) -> str:
    return json.dumps(value, ensure_ascii=False, indent=2, sort_keys=True) + "\n"


def expected_paths(specs: list[ScenarioSpec]) -> set[Path]:
    return {SCENARIOS / spec.scenario_id / relative for spec in specs for relative in spec.files}


def assert_generated_root() -> None:
    resolved = SCENARIOS.resolve(strict=False)
    expected = (REPO / "demo" / "scenarios").resolve(strict=False)
    if resolved != expected or REPO not in resolved.parents:
        raise RuntimeError(f"refusing to modify unexpected demo root: {resolved}")


def write_assets(specs: list[ScenarioSpec]) -> None:
    assert_generated_root()
    expected = expected_paths(specs)
    SCENARIOS.mkdir(parents=True, exist_ok=True)
    for spec in specs:
        root = SCENARIOS / spec.scenario_id
        for relative, payload in spec.files.items():
            target = root / relative
            target.parent.mkdir(parents=True, exist_ok=True)
            target.write_bytes(payload)
    for path in sorted(SCENARIOS.rglob("*"), reverse=True):
        if path.is_file() and path not in expected:
            path.unlink()
        elif path.is_dir() and not any(path.iterdir()):
            path.rmdir()
    (DEMO / "assets-manifest.json").write_text(
        serialized(manifest(specs)), encoding="utf-8", newline="\n"
    )


def check_assets(specs: list[ScenarioSpec]) -> list[str]:
    errors: list[str] = []
    expected = expected_paths(specs)
    actual = (
        {path for path in SCENARIOS.rglob("*") if path.is_file()} if SCENARIOS.exists() else set()
    )
    for missing in sorted(expected - actual):
        errors.append(f"missing: {missing.relative_to(DEMO).as_posix()}")
    for extra in sorted(actual - expected):
        errors.append(f"unexpected: {extra.relative_to(DEMO).as_posix()}")
    for spec in specs:
        for relative, payload in spec.files.items():
            path = SCENARIOS / spec.scenario_id / relative
            if path.is_file() and path.read_bytes() != payload:
                errors.append(f"content drift: {path.relative_to(DEMO).as_posix()}")
    manifest_path = DEMO / "assets-manifest.json"
    if not manifest_path.is_file() or manifest_path.read_text(encoding="utf-8") != serialized(
        manifest(specs)
    ):
        errors.append("assets-manifest.json is missing or stale")
    return errors


def main() -> int:
    parser = argparse.ArgumentParser(
        description="Generate deterministic synthetic demo deliveries."
    )
    action = parser.add_mutually_exclusive_group(required=True)
    action.add_argument("--write", action="store_true", help="Regenerate demo scenarios in place.")
    action.add_argument("--check", action="store_true", help="Fail if demo assets drifted.")
    args = parser.parse_args()
    specs = scenario_specs()
    if args.write:
        write_assets(specs)
        print(f"generated {sum(len(item.files) for item in specs)} files in {len(specs)} scenarios")
        return 0
    errors = check_assets(specs)
    if errors:
        print("demo asset verification failed:")
        for error in errors:
            print(f"- {error}")
        return 1
    print(f"verified {sum(len(item.files) for item in specs)} files in {len(specs)} scenarios")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
